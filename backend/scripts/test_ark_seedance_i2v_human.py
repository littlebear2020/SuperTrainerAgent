#!/usr/bin/env python
"""Probe: is the seedance human-portrait block native to Ark, or a 360-gateway review layer?

Hypothesis (user): the ``InputImageSensitiveContentDetected.PrivacyInformation``
("may contain real person") rejection recorded at
  - service.py:447-451  (_resolve_vimax_video_backend docstring)
  - happyhorse.py:8-12 (live-verified: same realistic detective portrait blocked
    by 360-gateway seedance, accepted by happyhorse)
is added by the **360 gateway review layer** (api.360.cn,
``volcengine/doubao-seedance-2-0``), NOT by native Ark seedance
(``doubao-seedance-2-0-260128`` via ark.cn-beijing.volces.com).

Same-image A/B (clean source — image generated by Ark seedream t2i, which is
verified non-blocking, so the image itself is not the variable):
  1. Ark seedream t2i  -> realistic human portrait -> TOS signed URL.
  2. Ark-DIRECT seedance i2v with that image (POST /contents/generations/tasks).
  3. (if QIHU_API_KEY) 360-GATEWAY seedance r2v with the SAME image
     (POST /v1/videos/async_generations + extra_body.role=reference).

This script does NOT import or modify any product code — pure httpx + stdlib.
"""

import json
import os
import sys
import time
from pathlib import Path

import httpx


def _load_dotenv() -> None:
    """Minimal .env loader so the probe runs standalone (no source needed)."""
    for p in (Path(".env"), Path("../.env"), Path("../../.env")):
        if p.exists():
            for line in p.read_text().splitlines():
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip().strip('"').strip("'"))
            return


_load_dotenv()
ARK = os.environ.get("ARK_API_KEY", "").strip()
QIHU = os.environ.get("QIHU_API_KEY", "").strip()
ARK_BASE = "https://ark.cn-beijing.volces.com/api/v3"
QIHU_BASE = "https://api.360.cn"
VID_ARK = "doubao-seedance-2-0-260128"
IMG_ARK = "doubao-seedream-5-0-pro-260628"
VID_360 = "volcengine/doubao-seedance-2-0"


def banner(t: str) -> None:
    print(f"\n{'=' * 70}\n{t}\n{'=' * 70}", flush=True)


def _ark_headers() -> dict:
    return {"Authorization": f"Bearer {ARK}", "Content-Type": "application/json"}


def gen_human_portrait() -> str | None:
    banner("STEP 1: Ark seedream t2i -> realistic human portrait (clean source)")
    body = {"model": IMG_ARK, "prompt": "写实摄影半身肖像:一个戴黑色贝雷帽的年轻男子,清晰五官,自然光,电影感,真实照片质感"}
    r = httpx.post(f"{ARK_BASE}/images/generations", headers=_ark_headers(), json=body, timeout=120)
    print(f"HTTP {r.status_code}")
    print(r.text[:600])
    try:
        d = r.json()
        url = (d.get("data") or [{}])[0].get("url")
        if url:
            print(f"✅ portrait URL: {url[:90]}...")
        else:
            print("❌ no url in response")
        return url
    except Exception as e:
        print("parse err:", e)
        return None


def _poll(task_id: str, fetch, label: str, max_s: int = 300) -> dict | None:
    print(f"polling {label} task {task_id} (up to {max_s}s)...", flush=True)
    for i in range(max_s // 5):
        time.sleep(5)
        try:
            pr = fetch(task_id)
        except Exception as e:
            print(f"[{(i + 1) * 5}s] poll err: {e}")
            continue
        try:
            pd = pr.json()
        except Exception:
            print(f"[{(i + 1) * 5}s] HTTP {pr.status_code} body={pr.text[:200]}")
            continue
        st = pd.get("status") or (pd.get("data") or {}).get("status") or "?"
        print(f"[{(i + 1) * 5}s] status={st}", flush=True)
        low = str(st).lower()
        if low in ("succeeded", "succeed", "completed", "failed", "fail", "error"):
            print(f"FINAL {label}:", json.dumps(pd, ensure_ascii=False)[:1500])
            return pd
    print(f"⏱️ {label} timeout after {max_s}s")
    return None


def ark_seedance_i2v(image_url: str, prompt: str) -> dict | None:
    banner("STEP 2: Ark-DIRECT seedance i2v (native Ark — NO 360 gateway)")
    body = {
        "model": VID_ARK,
        "content": [
            {"type": "text", "text": prompt},
            {"type": "image_url", "image_url": {"url": image_url}},
        ],
    }
    print("submit body:", json.dumps(body, ensure_ascii=False)[:300])
    r = httpx.post(f"{ARK_BASE}/contents/generations/tasks", headers=_ark_headers(), json=body, timeout=60)
    print(f"submit HTTP {r.status_code}")
    print(r.text[:800])
    task_id = None
    try:
        task_id = r.json().get("id")
    except Exception:
        pass
    if not task_id:
        print("❌ no task id returned — Ark i2v body shape may differ. Inspect raw above.")
        return None
    return _poll(task_id, lambda tid: httpx.get(f"{ARK_BASE}/contents/generations/tasks/{tid}", headers=_ark_headers(), timeout=30), "Ark", max_s=300)


def qihu_seedance_r2v(image_url: str, prompt: str) -> dict | None:
    banner("STEP 3: 360-GATEWAY seedance r2v (SAME image) — reproduce historical block?")
    body = {
        "model": VID_360,
        "content": [
            {"type": "text", "text": prompt},
            {"type": "image_url", "image_url": {"url": image_url}},
        ],
        "duration": 5,
        "extra_body": {"role": "reference"},
    }
    H = {"Authorization": f"Bearer {QIHU}", "Content-Type": "application/json"}
    print("submit body:", json.dumps(body, ensure_ascii=False)[:300])
    r = httpx.post(f"{QIHU_BASE}/v1/videos/async_generations", headers=H, json=body, timeout=60)
    print(f"submit HTTP {r.status_code}")
    print(r.text[:800])
    task_id = None
    try:
        task_id = (r.json().get("data") or {}).get("id")
    except Exception:
        pass
    if not task_id:
        print("❌ no task id returned (360 side)")
        return None
    Hg = {"Authorization": f"Bearer {QIHU}"}
    return _poll(task_id, lambda tid: httpx.get(f"{QIHU_BASE}/v1/videos/async_generations/{tid}", headers=Hg, timeout=30), "360", max_s=180)


def _outcome(j: dict | None) -> str:
    if j is None:
        return "NO_TASK"
    body = json.dumps(j, ensure_ascii=False).lower()
    st = str(j.get("status") or (j.get("data") or {}).get("status") or "").lower()
    if st in ("succeeded", "succeed", "completed"):
        return "SUCCEEDED"
    if "inputimagesensitive" in body or "privacyinformation" in body or "sensitivecontentdetected" in body:
        return "BLOCKED(content-review)"
    if st in ("failed", "fail", "error"):
        return f"FAILED({body[:220]})"
    return f"OTHER(status={st})"


def _verdict(ark: dict | None, qihu: dict | None) -> None:
    banner("VERDICT")
    a = _outcome(ark)
    q = _outcome(qihu) if qihu is not None else "SKIPPED(no QIHU key)"
    print(f"Ark-DIRECT seedance i2v  : {a}")
    print(f"360-GATEWAY seedance r2v : {q}")
    if a == "SUCCEEDED" and q.startswith("BLOCKED"):
        print("✅ HYPOTHESIS CONFIRMED: native Ark seedance i2v does NOT block the human portrait; the InputImageSensitiveContentDetected block is a 360-gateway review layer.")
    elif a.startswith("BLOCKED"):
        print("🔴 HYPOTHESIS REFUTED: native Ark seedance ALSO blocks the human portrait (not just the 360 gateway).")
    elif a == "SUCCEEDED":
        print(f"→ Ark i2v SUCCEEDED; 360 side = {q}. Compare to decide whether 360 adds an extra block.")
    else:
        print(f"→ inconclusive: Ark={a}, 360={q}. Inspect raw outputs above.")


if __name__ == "__main__":
    if not ARK:
        print("❌ ARK_API_KEY not set (.env at repo root or env)")
        sys.exit(1)
    print(f"ARK key: {ARK[:10]}...{ARK[-4:]}  | 360 key: {'SET' if QIHU else 'ABSENT (skip 360 side)'}")
    prompt = "这个男子微微转头,自然呼吸,电影感运镜,写实"
    img = gen_human_portrait()
    if not img:
        print("❌ cannot proceed without a portrait image")
        sys.exit(1)
    ark = ark_seedance_i2v(img, prompt)
    q = qihu_seedance_r2v(img, prompt) if QIHU else None
    _verdict(ark, q)
    print("\n=== probe complete ===")
